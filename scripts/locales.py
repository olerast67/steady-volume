def main():
    en = json.load(io.open(LOCALES / "en" / "messages.json", encoding="utf-8"))
    for lang, strings in T.items():
        missing = set(en) - set(strings)
        extra = set(strings) - set(en)
        assert not missing and not extra, (lang, missing, extra)
        out = {}
        for key in en:
            msg = strings[key]
            for ph in re.findall(r"\$\d", en[key]["message"]):
                assert ph in msg, (lang, key, ph)
            msg = re.sub(r"(\$\d) (LUFS|dB|дБ)", lambda m: m.group(1) + NBSP + m.group(2), msg)
            out[key] = {"message": msg}
        assert len(out["extName"]["message"]) <= 75, (lang, "extName too long")
        assert len(out["extDescription"]["message"]) <= 132, (lang, "extDescription", len(out["extDescription"]["message"]))
        (LOCALES / lang).mkdir(exist_ok=True)
        with io.open(LOCALES / lang / "messages.json", "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write("\n")
    print("written:", ", ".join(T))


